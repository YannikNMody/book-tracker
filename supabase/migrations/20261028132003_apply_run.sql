-- ---------------------------------------------------------------------
-- 1. Run identity and apply tracking
-- ---------------------------------------------------------------------
alter table public.scrape_runs
    add column run_uuid   uuid unique,
    add column applied_at timestamptz;

comment on column public.scrape_runs.run_uuid   is 'Generated by the scraper; loading the same output file twice is a no-op.';
comment on column public.scrape_runs.applied_at is 'When apply_run() merged this run into books / price_history / stock_history. Null = not merged.';


-- ---------------------------------------------------------------------
-- 2. Indexes for foreign keys pointing at scrape_runs
-- ---------------------------------------------------------------------
create index books_first_seen_run_idx on public.books (first_seen_run_id);
create index books_last_seen_run_idx  on public.books (last_seen_run_id);
create index price_history_run_idx    on public.price_history (detected_in_run_id);
create index stock_history_run_idx    on public.stock_history (detected_in_run_id);


-- ---------------------------------------------------------------------
-- 3. updated_at = "descriptive data last changed", not "last seen"
--    (every run touches last_seen_*, which must not bump updated_at)
-- ---------------------------------------------------------------------
create or replace function public.books_touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    if (new.title, new.category_id, new.rating, new.description, new.product_type,
        new.num_reviews, new.image_url, new.product_url, new.is_active)
       is distinct from
       (old.title, old.category_id, old.rating, old.description, old.product_type,
        old.num_reviews, old.image_url, old.product_url, old.is_active)
    then
        new.updated_at = now();
    else
        new.updated_at = old.updated_at;
    end if;
    return new;
end;
$$;

drop trigger books_set_updated_at on public.books;
drop function public.set_updated_at();

create trigger books_touch_updated_at
    before update on public.books
    for each row execute function public.books_touch_updated_at();


-- ---------------------------------------------------------------------
-- 4. apply_run: merge one run's staging rows into the real tables
--
--    Called by the loader inside the same transaction that inserted the
--    run and its staging rows, so a run lands completely or not at all.
--
--    Rules
--    * runs of a source must be applied in chronological order
--    * a run can be applied only once
--    * price / stock history get a new row only when the value changes:
--      the current row is closed (valid_to) and a new current row opened
--    * missing values in a scrape never overwrite known values (coalesce)
--    * only a complete, successful full run may mark unseen books inactive,
--      and only if it saw at least half of the active catalogue
--      (circuit breaker against a broken page layout wiping the catalogue)
-- ---------------------------------------------------------------------
create or replace function public.apply_run(p_run_id bigint)
returns jsonb
language plpgsql
set search_path = ''
as $$
declare
    v_run              public.scrape_runs%rowtype;
    v_categories_new   integer := 0;
    v_books_seen       integer := 0;
    v_books_new        integer := 0;
    v_price_changes    integer := 0;
    v_prices_inserted  integer := 0;
    v_stock_changes    integer := 0;
    v_stock_inserted   integer := 0;
    v_active_before    integer := 0;
    v_delisted         integer := 0;
    v_delisting        text    := 'not_a_full_run';
    v_summary          jsonb;
begin
    -- Lock the run row so two loaders cannot apply it concurrently
    select * into v_run from public.scrape_runs where id = p_run_id for update;
    if not found then
        raise exception 'scrape run % does not exist', p_run_id;
    end if;
    if v_run.applied_at is not null then
        raise exception 'scrape run % was already applied at %', p_run_id, v_run.applied_at;
    end if;
    if exists (
        select 1 from public.scrape_runs r
        where r.source_id = v_run.source_id
          and r.applied_at is not null
          and r.started_at > v_run.started_at
    ) then
        raise exception 'a newer run of this source is already applied; apply runs in chronological order (run % started %)',
            p_run_id, v_run.started_at;
    end if;

    select count(*) into v_active_before
    from public.books where source_id = v_run.source_id and is_active;

    -- Categories -------------------------------------------------------
    insert into public.categories (source_id, name)
    select distinct v_run.source_id, s.category_name
    from public.staging_observations s
    where s.run_id = p_run_id and s.category_name is not null
    on conflict (source_id, name) do nothing;
    get diagnostics v_categories_new = row_count;

    -- Books: insert new, refresh existing --------------------------------
    with upserted as (
        insert into public.books as b (
            source_id, external_id, title, category_id, rating, description,
            product_type, num_reviews, image_url, product_url, is_active,
            first_seen_at, last_seen_at, first_seen_run_id, last_seen_run_id)
        select
            v_run.source_id, s.external_id, s.title, c.id, s.rating, s.description,
            s.product_type, s.num_reviews, s.image_url, s.product_url, true,
            s.scraped_at, s.scraped_at, p_run_id, p_run_id
        from public.staging_observations s
        left join public.categories c
               on c.source_id = v_run.source_id and c.name = s.category_name
        where s.run_id = p_run_id
        on conflict (source_id, external_id) do update set
            title            = excluded.title,
            category_id      = coalesce(excluded.category_id,  b.category_id),
            rating           = coalesce(excluded.rating,       b.rating),
            description      = coalesce(excluded.description,  b.description),
            product_type     = coalesce(excluded.product_type, b.product_type),
            num_reviews      = coalesce(excluded.num_reviews,  b.num_reviews),
            image_url        = coalesce(excluded.image_url,    b.image_url),
            product_url      = excluded.product_url,
            is_active        = true,
            last_seen_at     = greatest(b.last_seen_at, excluded.last_seen_at),
            last_seen_run_id = excluded.last_seen_run_id
        returning (xmax = 0) as is_new
    )
    select count(*), count(*) filter (where is_new)
    into v_books_seen, v_books_new
    from upserted;

    -- Prices: close the current row where the observed price differs ------
    update public.price_history p
       set valid_to = o.scraped_at
      from (
            select b.id as book_id, s.price_excl_tax, s.price_incl_tax, s.currency, s.scraped_at
            from public.staging_observations s
            join public.books b on b.source_id = v_run.source_id and b.external_id = s.external_id
            where s.run_id = p_run_id
              and s.price_excl_tax is not null and s.price_incl_tax is not null and s.currency is not null
           ) o
     where p.book_id = o.book_id
       and p.valid_to is null
       and (p.price_excl_tax, p.price_incl_tax, p.currency)
           is distinct from (o.price_excl_tax, o.price_incl_tax, o.currency);
    get diagnostics v_price_changes = row_count;

    -- ... then open a current row wherever none exists (new books + changed prices)
    insert into public.price_history
        (book_id, price_excl_tax, price_incl_tax, currency, valid_from, detected_in_run_id)
    select o.book_id, o.price_excl_tax, o.price_incl_tax, o.currency, o.scraped_at, p_run_id
    from (
            select b.id as book_id, s.price_excl_tax, s.price_incl_tax, s.currency, s.scraped_at
            from public.staging_observations s
            join public.books b on b.source_id = v_run.source_id and b.external_id = s.external_id
            where s.run_id = p_run_id
              and s.price_excl_tax is not null and s.price_incl_tax is not null and s.currency is not null
         ) o
    where not exists (
        select 1 from public.price_history p where p.book_id = o.book_id and p.valid_to is null
    );
    get diagnostics v_prices_inserted = row_count;

    -- Stock: same pattern --------------------------------------------------
    update public.stock_history h
       set valid_to = o.scraped_at
      from (
            select b.id as book_id, s.in_stock, s.quantity, s.scraped_at
            from public.staging_observations s
            join public.books b on b.source_id = v_run.source_id and b.external_id = s.external_id
            where s.run_id = p_run_id and s.in_stock is not null
           ) o
     where h.book_id = o.book_id
       and h.valid_to is null
       and (h.in_stock, h.quantity) is distinct from (o.in_stock, o.quantity);
    get diagnostics v_stock_changes = row_count;

    insert into public.stock_history (book_id, in_stock, quantity, valid_from, detected_in_run_id)
    select o.book_id, o.in_stock, o.quantity, o.scraped_at, p_run_id
    from (
            select b.id as book_id, s.in_stock, s.quantity, s.scraped_at
            from public.staging_observations s
            join public.books b on b.source_id = v_run.source_id and b.external_id = s.external_id
            where s.run_id = p_run_id and s.in_stock is not null
         ) o
    where not exists (
        select 1 from public.stock_history h where h.book_id = o.book_id and h.valid_to is null
    );
    get diagnostics v_stock_inserted = row_count;

    -- Delisting --------------------------------------------------------------
    if v_run.is_full_run and v_run.status = 'success' then
        if v_active_before > 0 and v_books_seen < v_active_before * 0.5 then
            v_delisting := 'skipped_circuit_breaker';
        else
            update public.books
               set is_active = false
             where source_id = v_run.source_id
               and is_active
               and last_seen_run_id is distinct from p_run_id;
            get diagnostics v_delisted = row_count;
            v_delisting := 'applied';
        end if;
    end if;

    v_summary := jsonb_build_object(
        'books_seen',            v_books_seen,
        'books_new',             v_books_new,
        'categories_new',        v_categories_new,
        'price_changes',         v_price_changes,
        'prices_first_recorded', v_prices_inserted - v_price_changes,
        'stock_changes',         v_stock_changes,
        'stock_first_recorded',  v_stock_inserted - v_stock_changes,
        'books_delisted',        v_delisted,
        'delisting',             v_delisting
    );

    update public.scrape_runs
       set applied_at    = now(),
           books_new     = v_books_new,
           price_changes = v_price_changes,
           stock_changes = v_stock_changes,
           stats         = stats || jsonb_build_object('apply', v_summary)
     where id = p_run_id;

    return v_summary;
end;
$$;

comment on function public.apply_run(bigint) is
    'Merges one scrape run from staging_observations into categories, books, price_history and stock_history. Called by the loader.';


-- ---------------------------------------------------------------------
-- 5. Privileges: functions in public are executable by everyone and
--    exposed over the API by default. Only the backend may run these.
-- ---------------------------------------------------------------------
revoke execute on function public.apply_run(bigint)         from public, anon, authenticated;
revoke execute on function public.books_touch_updated_at()  from public, anon, authenticated;
grant  execute on function public.apply_run(bigint)         to service_role;
