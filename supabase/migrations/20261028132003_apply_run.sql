--   * run identity (load the same file twice = no-op) and apply tracking
--   * indexes for the foreign keys to scrape_runs (performance advisor)
--   * books.updated_at only moves when descriptive data actually changes
--   * apply_run(run_id): set-based merge of one run from staging into
--     categories / books / price_history / stock_history
